namespace RedFox.GameExtraction.UI;

/// <summary>
/// Identifies the colour theme used by the GameExtraction interface.
/// </summary>
public enum InterfaceTheme
{
    /// <summary>
    /// The default dark theme.
    /// </summary>
    Dark,

    /// <summary>
    /// The light theme.
    /// </summary>
    Light,

    /// <summary>
    /// The dark high contrast theme.
    /// </summary>
    HighContrast,

    /// <summary>
    /// Follows the operating system's light, dark, and high contrast preferences.
    /// </summary>
    System,
}
